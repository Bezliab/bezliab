/**
 * Writes src/data/imageSizes.js — the pixel size of every image in public/img.
 *
 * The layout uses these to give each picture its exact shape *before* it
 * loads, so cards match their images with no bars, no cropping and no
 * jumping. It runs automatically before `npm run dev` and `npm run build`
 * (see the "predev" / "prebuild" scripts), so dropping a new image into
 * public/img needs no extra step.
 *
 * Reads file headers only (WebP and PNG) — no dependencies.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, extname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const imgDir = join(root, 'public', 'img')
const outFile = join(root, 'src', 'data', 'imageSizes.js')

function webpSize(b) {
  if (b.toString('ascii', 0, 4) !== 'RIFF' || b.toString('ascii', 8, 12) !== 'WEBP') return null
  const type = b.toString('ascii', 12, 16)
  if (type === 'VP8X') return [1 + b.readUIntLE(24, 3), 1 + b.readUIntLE(27, 3)]
  if (type === 'VP8L') {
    const bits = b.readUInt32LE(21)
    return [(bits & 0x3fff) + 1, ((bits >> 14) & 0x3fff) + 1]
  }
  if (type === 'VP8 ') return [b.readUInt16LE(26) & 0x3fff, b.readUInt16LE(28) & 0x3fff]
  return null
}

function pngSize(b) {
  if (b.toString('ascii', 1, 4) !== 'PNG') return null
  return [b.readUInt32BE(16), b.readUInt32BE(20)]
}

const sizes = {}
for (const file of readdirSync(imgDir).sort()) {
  const ext = extname(file).toLowerCase()
  if (ext !== '.webp' && ext !== '.png') continue
  const buf = readFileSync(join(imgDir, file))
  const size = ext === '.webp' ? webpSize(buf) : pngSize(buf)
  if (size) sizes[`/img/${file}`] = size
  else console.warn(`[image-sizes] could not read ${file}`)
}

const body = Object.entries(sizes)
  .map(([k, [w, h]]) => `  ${JSON.stringify(k)}: [${w}, ${h}],`)
  .join('\n')

writeFileSync(
  outFile,
  `// GENERATED by scripts/generate-image-sizes.mjs — do not edit by hand.\n` +
    `// Maps each image in public/img to its [width, height] in pixels.\n` +
    `export const imageSizes = {\n${body}\n}\n`
)
console.log(`[image-sizes] ${Object.keys(sizes).length} images`)
